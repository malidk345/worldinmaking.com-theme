const importedSrc = (mod: unknown): string => {
  if (typeof mod === 'string') return mod
  if (mod && typeof mod === 'object' && 'src' in mod) {
    const src = (mod as { src?: unknown }).src
    if (typeof src === 'string') return src
  }
  return ''
}

